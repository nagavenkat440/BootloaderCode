void uartLoopBack_test(uint8_t value)
{
	if(value == 1)
	{
		HAL_GPIO_WritePin(RS422_LOOP_IN1_GPIO_Port,RS422_LOOP_IN1_Pin,GPIO_PIN_SET);
		HAL_GPIO_WritePin(RS422_LOOP_IN2_GPIO_Port,RS422_LOOP_IN2_Pin,GPIO_PIN_SET);
		HAL_GPIO_WritePin(RS422_LOOP_IN3_GPIO_Port,RS422_LOOP_IN3_Pin,GPIO_PIN_SET);
		HAL_GPIO_WritePin(RS422_LOOP_IN4_GPIO_Port,RS422_LOOP_IN4_Pin,GPIO_PIN_SET);

		//uart data transmit for uart loopback check
		RS422_1_TX_EN;
		HAL_UART_Transmit(&huart1, tx1_data, 5, HAL_MAX_DELAY);
		RS422_1_RX_EN;
		RS422_2_TX_EN;
		HAL_UART_Transmit(&huart2, tx2_data, 5, HAL_MAX_DELAY);
		RS422_2_RX_EN;
	}
	else{

		HAL_GPIO_WritePin(RS422_LOOP_IN1_GPIO_Port,RS422_LOOP_IN1_Pin,GPIO_PIN_RESET);
		HAL_GPIO_WritePin(RS422_LOOP_IN2_GPIO_Port,RS422_LOOP_IN2_Pin,GPIO_PIN_RESET);
		HAL_GPIO_WritePin(RS422_LOOP_IN3_GPIO_Port,RS422_LOOP_IN3_Pin,GPIO_PIN_RESET);
		HAL_GPIO_WritePin(RS422_LOOP_IN4_GPIO_Port,RS422_LOOP_IN4_Pin,GPIO_PIN_RESET);
	}
}
